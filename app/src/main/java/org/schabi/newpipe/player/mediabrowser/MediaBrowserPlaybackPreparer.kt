/**
 * This class is used to cleanly separate the Service implementation (in
 * [org.schabi.newpipe.player.PlayerService]) and the playback preparer implementation (in this
 * file). We currently use the playback preparer only in conjunction with the media browser: the
 * playback preparer will receive the media URLs generated by [MediaBrowserImpl] and will start
 * playback of the corresponding streams or playlists.
 *
 * @param setMediaSessionError takes an error String and a Media3 session error code.
 * @param clearMediaSessionError clears any previously reported media session error.
 * @param onPrepare takes playWhenReady and calls the app player preparation path used by media
 * session prepare commands.
 */
class MediaBrowserPlaybackPreparer(
    private val context: Context,
    private val setMediaSessionError: BiConsumer<CharSequence, Int>, // error string, error code
    private val clearMediaSessionError: Runnable,
    private val onPrepare: Consumer<Boolean>
) {
    private val database = NewPipeDatabase.getInstance(context)
    private val catalogRepository = MusicCatalogRepository()
    private var disposable: Disposable? = null

    fun dispose() {
        disposable?.dispose()
    }

    //region Media session prepare commands
    fun onPrepare(playWhenReady: Boolean) {
        onPrepare.accept(playWhenReady)
    }

    fun onPrepareFromMediaId(mediaId: String, playWhenReady: Boolean, extras: Bundle?) {
        if (MainActivity.DEBUG) {
            Log.d(TAG, "onPrepareFromMediaId($mediaId, $playWhenReady, $extras)")
        }

        disposable?.dispose()
        disposable = extractPlayQueueFromMediaId(mediaId)
            .subscribeOn(Schedulers.io())
            .observeOn(AndroidSchedulers.mainThread())
            .subscribe(
                { playQueue ->
                    clearMediaSessionError.run()
                    NavigationHelper.playOnBackgroundPlayer(context, playQueue, playWhenReady)
                },
                { throwable ->
                    Log.e(TAG, "Failed to start playback of media ID [$mediaId]", throwable)
                    onPrepareError(throwable)
                }
            )
    }

    fun onPrepareFromSearch(query: String, playWhenReady: Boolean, extras: Bundle?) {
        if (MainActivity.DEBUG) {
            Log.d(TAG, "onPrepareFromSearch($query, $playWhenReady, $extras)")
        }

        disposable?.dispose()
        disposable = extractPlayQueueFromSearch(query, extras)
            .subscribeOn(Schedulers.io())
            .observeOn(AndroidSchedulers.mainThread())
            .subscribe(
                { playQueue ->
                    clearMediaSessionError.run()
                    NavigationHelper.playOnBackgroundPlayer(context, playQueue, playWhenReady)
                },
                { throwable ->
                    Log.e(TAG, "Failed to start playback from search [$query]", throwable)
                    onPrepareError(throwable)
                }
            )
    }

    fun onPrepareFromUri(uri: Uri, playWhenReady: Boolean, extras: Bundle?) {
        onUnsupportedError()
    }
    //endregion

    //region Errors
    private fun onUnsupportedError() {
        setMediaSessionError.accept(
            ContextCompat.getString(context, R.string.content_not_supported),
            SessionResult.RESULT_ERROR_NOT_SUPPORTED
        )
    }

    private fun onPrepareError(throwable: Throwable) {
        setMediaSessionError.accept(
            ErrorInfo.getMessage(throwable, null, null).getText(context),
            SessionResult.RESULT_ERROR_UNKNOWN
        )
    }
    //endregion

    //region Building play queues from playlists and history
    private fun extractLocalPlayQueue(playlistId: Long, index: Int): Single<PlayQueue> {
        return LocalPlaylistManager(database).getPlaylistStreams(playlistId).firstOrError()
            .map { items -> SinglePlayQueue(items.map { it.toStreamInfoItem() }, index) }
    }

    private fun extractRemotePlayQueue(playlistId: Long, index: Int): Single<PlayQueue> {
        return RemotePlaylistManager(database).getPlaylist(playlistId).firstOrError()
            .flatMap { ExtractorHelper.getPlaylistInfo(it.serviceId, it.url, false) }
            // ignore info.errors, i.e. ignore errors about specific items, since there would
            // be no way to show the error properly in Android Auto anyway
            .map { info -> PlaylistPlayQueue(info, index) }
    }

    private fun extractPlayQueueFromMediaId(mediaId: String): Single<PlayQueue> {
        try {
            val mediaIdUri = mediaId.toUri()
            val path = ArrayList(mediaIdUri.pathSegments)
            if (path.isEmpty()) {
                throw parseError(mediaId)
            }

            return when (path.removeAt(0)) {
                ID_BOOKMARKS -> extractPlayQueueFromPlaylistMediaId(
                    mediaId,
                    path,
                    mediaIdUri.getQueryParameter(ID_URL)
                )

                ID_HISTORY -> extractPlayQueueFromHistoryMediaId(mediaId, path)

                ID_INFO_ITEM -> extractPlayQueueFromInfoItemMediaId(
                    mediaId,
                    path,
                    mediaIdUri.getQueryParameter(ID_URL) ?: throw parseError(mediaId)
                )

                ID_CATALOG -> extractCatalogPlayQueue(mediaId, path)

                else -> throw parseError(mediaId)
            }
        } catch (e: ContentNotAvailableException) {
            return Single.error(e)
        }
    }

    @Throws(ContentNotAvailableException::class)
    private fun extractPlayQueueFromPlaylistMediaId(
        mediaId: String,
        path: MutableList<String>,
        url: String?
    ): Single<PlayQueue> {
        if (path.isEmpty()) {
            throw parseError(mediaId)
        }

        when (val playlistType = path.removeAt(0)) {
            ID_LOCAL, ID_REMOTE -> {
                if (path.size != 2) {
                    throw parseError(mediaId)
                }
                val playlistId = path[0].toLong()
                val index = path[1].toInt()
                return if (playlistType == ID_LOCAL) {
                    extractLocalPlayQueue(playlistId, index)
                } else {
                    extractRemotePlayQueue(playlistId, index)
                }
            }

            ID_URL -> {
                if (path.size != 1 || url == null) {
                    throw parseError(mediaId)
                }

                val serviceId = path[0].toInt()
                return ExtractorHelper.getPlaylistInfo(serviceId, url, false)
                    .map { PlaylistPlayQueue(it) }
            }

            else -> throw parseError(mediaId)
        }
    }

    @Throws(ContentNotAvailableException::class)
    private fun extractPlayQueueFromHistoryMediaId(
        mediaId: String,
        path: List<String>
    ): Single<PlayQueue> {
        if (path.size != 1) {
            throw parseError(mediaId)
        }

        val streamId = path[0].toLong()
        return database.streamHistoryDAO().history
            .firstOrError()
            .map { items ->
                val infoItems = items
                    .filter { it.streamId == streamId }
                    .map { it.toStreamInfoItem() }
                SinglePlayQueue(infoItems, 0)
            }
    }

    @Throws(ContentNotAvailableException::class)
    private fun extractPlayQueueFromInfoItemMediaId(
        mediaId: String,
        path: List<String>,
        url: String
    ): Single<PlayQueue> {
        if (path.size != 2) {
            throw parseError(mediaId)
        }

        val serviceId = path[1].toInt()
        return when (infoItemTypeFromString(path[0])) {
            InfoType.STREAM -> ExtractorHelper.getStreamInfo(context, serviceId, url, false)
                .map { SinglePlayQueue(it) }

            InfoType.PLAYLIST -> ExtractorHelper.getPlaylistInfo(serviceId, url, false)
                .map { PlaylistPlayQueue(it) }

            InfoType.CHANNEL -> ExtractorHelper.getChannelInfo(serviceId, url, false)
                .map { info ->
                    val playableTab = info.tabs
                        .firstOrNull { ChannelTabHelper.isStreamsTab(it) }
                        ?: throw ContentNotAvailableException("No streams tab found")
                    return@map ChannelTabPlayQueue(serviceId, ListLinkHandler(playableTab))
                }

            else -> throw parseError(mediaId)
        }
    }

    private fun extractCatalogPlayQueue(
        mediaId: String,
        path: List<String>
    ): Single<PlayQueue> {
        if (path.size != 2) {
            return Single.error(parseError(mediaId))
        }
        return Single.fromCallable {
            val playlist = catalogRepository.loadCatalog(context).getPlaylist(path[0])
                ?: throw parseError(mediaId)
            val index = path[1].toIntOrNull() ?: throw parseError(mediaId)
            if (index !in playlist.songs.indices) {
                throw parseError(mediaId)
            }
            InfiniteMusicPlayQueue(playlist, index)
        }
    }

    private fun extractPlayQueueFromSearch(query: String?, extras: Bundle?): Single<PlayQueue> {
        val voiceQueries = listOfNotNull(
            extras?.getString(android.provider.MediaStore.EXTRA_MEDIA_PLAYLIST),
            extras?.getString(android.provider.MediaStore.EXTRA_MEDIA_TITLE),
            extras?.getString(android.provider.MediaStore.EXTRA_MEDIA_ARTIST),
            extras?.getString(android.provider.MediaStore.EXTRA_MEDIA_ALBUM),
            extras?.getString(android.provider.MediaStore.EXTRA_MEDIA_GENRE),
            query
        ).map(String::trim).filter(String::isNotBlank).distinct()

        if (voiceQueries.isEmpty()) {
            return defaultCatalogQueue() ?: database.streamHistoryDAO().history
                .firstOrError()
                .map { items ->
                    SinglePlayQueue(
                        items.take(12).map { it.toStreamInfoItem() },
                        0
                    )
                }
        }

        for (voiceQuery in voiceQueries) {
            findCatalogQueue(voiceQuery)?.let { return Single.just(it) }
        }

        val serviceId = ServiceHelper.getSelectedServiceId(context)
        return ExtractorHelper.searchFor(serviceId, voiceQueries.first(), listOf(), "")
            .map { search ->
                val stream = search.relatedItems.filterIsInstance<StreamInfoItem>().firstOrNull()
                    ?: throw ContentNotAvailableException(
                        "No playable stream found for search query: ${voiceQueries.first()}"
                    )
                SinglePlayQueue(stream)
            }
    }

    private fun defaultCatalogQueue(): Single<PlayQueue>? {
        return try {
            val playlist = catalogRepository.loadCatalog(context).allPlaylists.firstOrNull()
                ?: return null
            Single.just(InfiniteMusicPlayQueue(playlist))
        } catch (exception: Exception) {
            Log.w(TAG, "Could not load default iradu playlist", exception)
            null
        }
    }

    private fun findCatalogQueue(query: String): PlayQueue? {
        val catalog = try {
            catalogRepository.loadCatalog(context)
        } catch (exception: Exception) {
            Log.w(TAG, "Could not load the iradu catalog for voice search", exception)
            return null
        }

        for (playlist in catalog.allPlaylists) {
            if (MusicVoiceSearchMatcher.matchesPlaylist(
                    query,
                    playlist.title,
                    playlist.subtitle,
                    playlist.description
                )
            ) {
                return InfiniteMusicPlayQueue(playlist, 0)
            }
        }

        for (playlist in catalog.allPlaylists) {
            for ((index, song) in playlist.songs.withIndex()) {
                if (MusicVoiceSearchMatcher.matchesSong(
                        query,
                        song.title,
                        song.artist,
                        song.album,
                        playlist.title
                    )
                ) {
                    return InfiniteMusicPlayQueue(playlist, index)
                }
            }
        }
        return null
    }
    //endregion

    companion object {
        private val TAG = MediaBrowserPlaybackPreparer::class.simpleName
    }
}
